CREATE TABLE IF NOT EXISTS public.nudo_inventory_receipts (
  reference text PRIMARY KEY,
  items jsonb NOT NULL,
  notes text NOT NULL DEFAULT '',
  result jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.nudo_inventory_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL,
  product_name text NOT NULL,
  movement_type text NOT NULL CHECK (movement_type IN ('purchase', 'sale', 'adjustment')),
  quantity bigint NOT NULL CHECK (quantity > 0),
  stock_before bigint NOT NULL CHECK (stock_before >= 0),
  stock_after bigint NOT NULL CHECK (stock_after >= 0),
  reference text NOT NULL,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS nudo_inventory_movements_created_at_idx
  ON public.nudo_inventory_movements (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS nudo_inventory_movements_product_idx
  ON public.nudo_inventory_movements (product_id, created_at DESC, id DESC);

ALTER TABLE public.nudo_inventory_receipts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nudo_inventory_movements ENABLE ROW LEVEL SECURITY;
