  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'REVOKE ALL ON public.nudo_inventory_receipts FROM authenticated';
    EXECUTE 'REVOKE ALL ON public.nudo_inventory_movements FROM authenticated';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    EXECUTE 'GRANT SELECT ON public.nudo_inventory_movements TO service_role';
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.nudo_log_inventory_movement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  before_stock bigint := 0;
  after_stock bigint := 0;
  movement_quantity bigint;
  movement_kind text := 'adjustment';
  movement_reference text;
  movement_notes text := 'Ajuste de inventario';
  row_reference text;
  row_notes text;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF coalesce(OLD.data->>'stock', '0') !~ '^(0|[1-9][0-9]*)$'
       OR coalesce(NEW.data->>'stock', '0') !~ '^(0|[1-9][0-9]*)$' THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_PRODUCT_STOCK';
    END IF;
    before_stock := coalesce((OLD.data->>'stock')::bigint, 0);
  END IF;
  IF coalesce(NEW.data->>'stock', '0') !~ '^(0|[1-9][0-9]*)$' THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_PRODUCT_STOCK';
  END IF;
  after_stock := coalesce((NEW.data->>'stock')::bigint, 0);
  IF before_stock = after_stock THEN
    RETURN NEW;
  END IF;

  movement_quantity := abs(after_stock - before_stock);
  movement_reference := 'AJUSTE-' || txid_current()::text;
  IF TG_OP = 'INSERT' THEN
    movement_notes := 'Stock inicial';
  ELSIF after_stock < before_stock THEN
    SELECT orders.order_id INTO row_reference
    FROM public.nudo_inventory_orders AS orders
    CROSS JOIN LATERAL jsonb_array_elements(orders.items) AS item(value)
    WHERE orders.result IS NULL
      AND item.value->>'id' = NEW.id
      AND (item.value->>'quantity')::bigint = before_stock - after_stock
    ORDER BY orders.created_at DESC
    LIMIT 1;
    IF row_reference IS NOT NULL THEN
      movement_kind := 'sale';
      movement_reference := row_reference;
      movement_notes := 'Pedido confirmado';
    END IF;
  ELSE
    SELECT receipts.reference, receipts.notes INTO row_reference, row_notes
    FROM public.nudo_inventory_receipts AS receipts
    CROSS JOIN LATERAL jsonb_array_elements(receipts.items) AS item(value)
    WHERE receipts.result IS NULL
      AND item.value->>'id' = NEW.id
      AND (item.value->>'quantity')::bigint = after_stock - before_stock
    ORDER BY receipts.created_at DESC
    LIMIT 1;
    IF row_reference IS NOT NULL THEN
      movement_kind := 'purchase';
      movement_reference := row_reference;
      movement_notes := row_notes;
    END IF;
  END IF;

  INSERT INTO public.nudo_inventory_movements (
    product_id, product_name, movement_type, quantity,
    stock_before, stock_after, reference, notes
  ) VALUES (
    NEW.id, coalesce(NEW.data->>'name', NEW.id), movement_kind, movement_quantity,
    before_stock, after_stock, movement_reference, movement_notes
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS nudo_inventory_movement_log ON public.products;
CREATE TRIGGER nudo_inventory_movement_log
AFTER INSERT OR UPDATE OF data ON public.products
FOR EACH ROW EXECUTE FUNCTION public.nudo_log_inventory_movement();

CREATE OR REPLACE FUNCTION public.nudo_receive_stock(
  p_reference text,
  p_items jsonb,
  p_notes text DEFAULT ''
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  item record;
  product_data jsonb;
  available bigint;
  updated_stock bigint;
  changes jsonb := '[]'::jsonb;
  normalized_items jsonb;
  saved_items jsonb;
  saved_notes text;
  saved_result jsonb;
  inserted_rows integer;
  normalized_notes text := coalesce(p_notes, '');
BEGIN
  IF p_reference IS NULL OR p_reference !~ '^COMPRA-[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}$'
     OR length(normalized_notes) > 500 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_RECEIPT';
  END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array'
     OR jsonb_array_length(p_items) < 1 OR jsonb_array_length(p_items) > 60 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_RECEIPT_ITEMS';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_items) AS entry(value)
    WHERE jsonb_typeof(value) IS DISTINCT FROM 'object'
       OR coalesce(value->>'id', '') !~ '^[a-z0-9]+(-[a-z0-9]+)*$'
       OR length(value->>'id') > 80
       OR coalesce(value->>'quantity', '') !~ '^[1-9][0-9]*$'
       OR (value->>'quantity')::numeric > 1000000000
  ) OR EXISTS (
    SELECT value->>'id'
    FROM jsonb_array_elements(p_items) AS entry(value)
    GROUP BY value->>'id'
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_RECEIPT_ITEMS';
  END IF;

  SELECT jsonb_agg(
    jsonb_build_object('id', value->>'id', 'quantity', (value->>'quantity')::bigint)
    ORDER BY value->>'id'
  )
  INTO normalized_items
  FROM jsonb_array_elements(p_items) AS entry(value);

  INSERT INTO public.nudo_inventory_receipts(reference, items, notes)
  VALUES (p_reference, normalized_items, normalized_notes)
  ON CONFLICT (reference) DO NOTHING;
  GET DIAGNOSTICS inserted_rows = ROW_COUNT;
  IF inserted_rows = 0 THEN
    SELECT items, notes, result
    INTO saved_items, saved_notes, saved_result
    FROM public.nudo_inventory_receipts
    WHERE reference = p_reference
    FOR UPDATE;
    IF saved_items IS DISTINCT FROM normalized_items OR saved_notes IS DISTINCT FROM normalized_notes THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'RECEIPT_REFERENCE_REUSED';
    END IF;
    RETURN saved_result;
  END IF;

  FOR item IN
    SELECT value->>'id' AS id, (value->>'quantity')::bigint AS quantity
    FROM jsonb_array_elements(normalized_items) AS entry(value)
    ORDER BY value->>'id'
  LOOP
    SELECT data INTO product_data
    FROM public.products
    WHERE id = item.id
    FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'PRODUCT_NOT_FOUND';
    END IF;
    IF coalesce(product_data->>'stock', '0') !~ '^(0|[1-9][0-9]*)$' THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_PRODUCT_STOCK';
    END IF;
    available := coalesce((product_data->>'stock')::bigint, 0);
    updated_stock := available + item.quantity;
    IF updated_stock > 1000000000 THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'STOCK_LIMIT_EXCEEDED';
    END IF;
    UPDATE public.products
    SET data = jsonb_set(data, '{stock}', to_jsonb(updated_stock), true)
    WHERE id = item.id;
    changes := changes || jsonb_build_array(
      jsonb_build_object('id', item.id, 'stock', updated_stock)
    );
  END LOOP;

  saved_result := jsonb_build_object('reference', p_reference, 'stock', changes);
  UPDATE public.nudo_inventory_receipts
  SET result = saved_result
  WHERE reference = p_reference;
  RETURN saved_result;
END;
$$;

